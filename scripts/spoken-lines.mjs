// Prints every spoken line on fixed sample data, English and Spanish, as Markdown for review.
// Usage: node scripts/spoken-lines.mjs > docs/SPOKEN-LINES-<date>.md
import { spoken, spokenIssues, SAMPLE_DATA } from "../server/spoken.mjs";

const describe = (kind, data) => {
  if (kind === "catalog") return data.catalog ? `catalog · ${data.query} in ${data.town}${data.missedTown ? ` (none in ${data.missedTown})` : ""} · ${data.count}` : `town · ${data.question}`;
  if (kind === "business") return `business · ${data.town} · ${data.mode}${data.topic ? ` · ${data.topic}` : ""}${data.proximity ? ` · nearby${data.proximity.reference ? "" : " (no reference)"}` : ""}${data.available ? "" : " · catalog missing"}`;
  if (kind === "chat") return `chat · ${data.kind}`;
  return kind;
};

console.log("# Spoken lines (what the voice says)\n");
console.log("Generated by `node scripts/spoken-lines.mjs` from `server/spoken.mjs`. The screen keeps the full sourced text; these are the spoken captions only.\n");
console.log("| Case | English | Español |\n|---|---|---|");
for (const [kind, data] of SAMPLE_DATA) {
  const en = spoken(kind, data, "en"), es = spoken(kind, data, "es");
  const flag = (line, lang) => { const issues = spokenIssues(line, lang); return issues.length ? ` ⚠ ${issues.join(",")}` : ""; };
  console.log(`| ${describe(kind, data)} | ${en}${flag(en, "en")} | ${es}${flag(es, "es")} |`);
}
